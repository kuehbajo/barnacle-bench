fn statemate_return(
    bitlist: &mut [i8; 64]
) -> bool {
    let mut checksum: u64 = 0;
    // loopbound min 64 max 64
    for i in (0..64).rev() {
        checksum += (bitlist[i] as u64) << i;
    }
    checksum == 32u64
}

// entrypoint
#[inline(never)]
#[unsafe(no_mangle)]
fn statemate_main(
    bitlist: &mut [i8; 64],
    stime: &mut u64,
    stable: &mut i8,
    step: &mut i8,
    data: &mut StatemateData,
    states: &mut StatemateStates,
) {
    statemate_FH_DU(
        bitlist, stime, stable, step, data, states
    );
}

#[cfg(all(target_arch = "arm", feature = "log"))]
const RUNS: usize = 2;

#[cfg(all(target_arch = "arm", feature = "log"))]
fn statemate_log(
    bitlist: &mut [i8; 64],
    stime: &mut u64,
    stable: &mut i8,
    step: &mut i8,
) -> bool {
    let mut run_cycles: [u32; RUNS] = [0; RUNS];

    let channels = rtt_init! {
        up: {
            0: {size: 1024, mode: ChannelMode::BlockIfFull,}
        }
    };
    set_print_channel(channels.up.0);

    run_cycles.iter_mut().for_each(|cycles| {
        let (mut data, mut states) = black_box(statemate_init(black_box(bitlist), black_box(stime)));
        let start = black_box(DWT::cycle_count());
        statemate_main(
            black_box(bitlist), black_box(stime),
            black_box(stable), black_box(step),
            black_box(&mut data), black_box(&mut states),
        );
        *cycles = black_box(DWT::cycle_count() - start);
    });

    run_cycles.iter().for_each(|cycles| {
        rprintln!("statemate - elapsed: {}", cycles);
    });

    black_box(statemate_return(black_box(bitlist)))
}

#[cfg(any(unix, windows, not(feature = "log")))]
fn statemate_std(
    bitlist: &mut [i8; 64],
    stime: &mut u64,
    stable: &mut i8,
    step: &mut i8,
) -> bool {
    let (mut data, mut states) = black_box(statemate_init(black_box(bitlist), black_box(stime)));
    statemate_main(
        black_box(bitlist), black_box(stime),
        black_box(stable), black_box(step),
        black_box(&mut data), black_box(&mut states),
    );
    black_box(statemate_return(black_box(bitlist)))
}

fn statemate() -> bool {
    static mut BITLIST: [i8; 64] = [0; 64];
    static mut STIME: u64 = 0;
    static mut STABLE: i8 = 0;
    static mut STEP: i8 = 0;
    // SAFETY: This is the only place we ever reference these and this function is never called again.
    let bitlist = unsafe { &mut *{ &raw mut BITLIST } };
    let stime = unsafe { &mut *{ &raw mut STIME } };
    let stable =  unsafe { &mut *{ &raw mut STABLE } };
    let step = unsafe { &mut *{ &raw mut STEP } };

    #[cfg(all(target_arch = "arm", feature = "log"))]
    {
        black_box(statemate_log(
            black_box(bitlist),
            black_box(stime),
            black_box(stable),
            black_box(step),
        ))
    }

    #[cfg(any(unix, windows, not(feature = "log")))]
    {
        black_box(statemate_std(
            black_box(bitlist),
            black_box(stime),
            black_box(stable),
            black_box(step),
        ))
    }
}

#[unsafe(no_mangle)]
#[cfg(target_arch = "arm")]
pub extern "C" fn main() {
    #[cfg_attr(not(feature = "log"), expect(unused_variables))]
    let success = black_box(statemate());
    
    #[cfg(feature = "log")]
    {
        rprintln!("statemate: {}", success);
        rprintln!("*STOP*{}", 1 - success as i32);
    }
}

