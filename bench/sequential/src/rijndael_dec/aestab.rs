/*
  used to ensure table is generated in the right format
  depending on the internal byte order required
*/

#[inline]
const fn r0(p: u8, q: u8, r: u8, s: u8) -> u32 {
    ((p as u32) << 24) | ((q as u32) << 16) | ((r as u32) << 8) | s as u32
}

#[inline]
const fn r1(p: u8, q: u8, r: u8, s: u8) -> u32 {
    p as u32 | ((q as u32) << 24) | ((r as u32) << 16) | ((s as u32) << 8)
}

#[inline]
const fn r2(p: u8, q: u8, r: u8, s: u8) -> u32 {
    ((p as u32) << 8) | q as u32 | ((r as u32) << 24) | ((s as u32) << 16)
}

#[inline]
const fn r3(p: u8, q: u8, r: u8, s: u8) -> u32 {
    ((p as u32) << 16) | ((q as u32) << 8) | r as u32 | ((s as u32) << 24)
}


